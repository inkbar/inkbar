/*
 * Writes src/icons.ts: the Lucide icons Inkbar uses, copied from the pinned `lucide`
 * devDependency so the package has no runtime dependency. Run `pnpm generate` after adding an
 * icon to ICONS or bumping `lucide`; src/icons.test.ts fails if the copy drifts.
 */
import { writeFileSync } from 'node:fs'

import * as lucide from 'lucide'

import { ICONS } from './icon-list'

const version = (
  (await import('lucide/package.json', { with: { type: 'json' } })) as {
    default: { version: string }
  }
).default.version

const body = ICONS.map((name) => {
  const node = (lucide as unknown as Record<string, unknown>)[name]
  if (!Array.isArray(node)) throw new Error(`lucide has no icon named ${name}`)
  return `export const ${name}: IconNode = ${JSON.stringify(node)}`
}).join('\n\n')

writeFileSync(
  new URL('../src/icons.ts', import.meta.url),
  `// Generated by scripts/generate.ts from lucide ${version}. Do not edit by hand.
// Lucide: ISC licence; some icons derive from Feather, MIT licence. See LICENSE.

import type { IconNode } from './types'

${body}
`
)
