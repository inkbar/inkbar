/*
 * Writes src/model/annotations/drawing/text/metrics-data.ts: the character widths of the
 * standard PDF fonts for the WinAnsi character set. Local only: never run in CI. The output is
 * committed.
 *
 *   pnpm --filter @inkbar/core generate:metrics
 *
 * The widths and the WinAnsi encoding come from @pdf-lib/standard-fonts (a devDependency
 * pinned to the version the file's header names).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import type * as StandardFonts from '@pdf-lib/standard-fonts'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(
  HERE,
  '..',
  'src',
  'model',
  'annotations',
  'drawing',
  'text',
  'metrics-data.ts'
)

const require = createRequire(import.meta.url)
const { Font, FontNames, Encodings } =
  require('@pdf-lib/standard-fonts') as typeof StandardFonts
const pkgPath = require.resolve('@pdf-lib/standard-fonts/package.json')
const pkg = JSON.parse(readFileSync(pkgPath, 'utf8')) as { version: string }
const licence = readFileSync(join(dirname(pkgPath), 'LICENSE.md'), 'utf8')
const copyright = /^Copyright .*$/m.exec(licence)?.[0]
if (!copyright) throw new Error('no copyright line in the source package licence')

const FACES = [
  ['helvetica', FontNames.Helvetica],
  ['helveticaBold', FontNames.HelveticaBold],
  ['helveticaItalic', FontNames.HelveticaOblique],
  ['helveticaBoldItalic', FontNames.HelveticaBoldOblique],
  ['times', FontNames.TimesRoman],
  ['timesBold', FontNames.TimesRomanBold],
  ['timesItalic', FontNames.TimesRomanItalic],
  ['timesBoldItalic', FontNames.TimesRomanBoldItalic],
  ['courier', FontNames.Courier],
  ['courierBold', FontNames.CourierBold],
  ['courierItalic', FontNames.CourierOblique],
  ['courierBoldItalic', FontNames.CourierBoldOblique],
] as const

const winAnsi = Encodings.WinAnsi
// Printable characters only. U+00AD (soft hyphen) is left out: the measure treats it as zero width.
const codePoints = [...winAnsi.supportedCodePoints]
  .filter((c) => c >= 0x20 && c !== 0x7f && c !== 0xad)
  .sort((a, b) => a - b)
if (!codePoints.includes(0x20ac)) throw new Error('the euro sign is missing from WinAnsi')

const widths = new Map<string, number[]>()
for (const [key, name] of FACES) {
  const font = Font.load(name)
  widths.set(
    key,
    codePoints.map((c) => {
      const glyph = winAnsi.encodeUnicodeCodePoint(c).name
      const w = font.getWidthOfGlyph(glyph)
      if (typeof w !== 'number' || !(w >= 0))
        throw new Error(`${name} has no width for U+${c.toString(16)} (${glyph})`)
      return w
    })
  )
}

const notice = /^Copyright .*?All Rights Reserved\./.exec(
  Font.load(FontNames.Helvetica).Notice
)?.[0]
if (!notice) throw new Error('no Adobe copyright notice in the font metrics')
const courier = new Set(
  ['courier', 'courierBold', 'courierItalic', 'courierBoldItalic'].map((k) =>
    widths.get(k)!.join()
  )
)
if (courier.size !== 1 || ![...courier][0]!.split(',').every((w) => w === '600'))
  throw new Error('the Courier faces are not all 600')

const arr = (key: string) => `[${widths.get(key)!.join(', ')}]`

const file = `/*
 * Generated by scripts/generate-font-metrics.ts. Do not edit; run \`pnpm --filter @inkbar/core generate:metrics\`.
 *
 * Character widths, in thousandths of the font size, of the standard PDF fonts (Helvetica,
 * Times and Courier, each in four faces) for the WinAnsi character set. Taken from
 * @pdf-lib/standard-fonts ${pkg.version}, which carries Adobe's metrics for these fonts.
 *
 * ${copyright} (@pdf-lib/standard-fonts, MIT licence)
 * ${notice}
 */

/** The characters the tables cover, in table order. */
export const CHARS =
  ${JSON.stringify(String.fromCodePoint(...codePoints))}

/** Widths per face in the order regular, bold, italic, bold italic; each indexed like \`CHARS\`. */
export const WIDTHS = {
  Helvetica: [
    ${arr('helvetica')},
    ${arr('helveticaBold')},
    ${arr('helveticaItalic')},
    ${arr('helveticaBoldItalic')},
  ],
  Times: [
    ${arr('times')},
    ${arr('timesBold')},
    ${arr('timesItalic')},
    ${arr('timesBoldItalic')},
  ],
} as const

/** Every Courier character, in every face. */
export const COURIER_WIDTH = 600
`
writeFileSync(OUT, file)
console.log(`wrote ${OUT} (${codePoints.length} characters)`)
